// BankAccount.java
//
// 이 파일은 "class"가 아니라 "interface" 입니다.
//
// class(클래스)  : 데이터(변수)와 그 데이터를 다루는 기능(메서드)을 실제로 구현한 "완성된 설계도"
// interface(인터페이스) : "이런 기능이 반드시 있어야 한다"는 약속(규칙)만 정의한 "빈 껍데기 설계도"
//
// 인터페이스 안에는 메서드의 이름과 매개변수, 반환 타입만 적혀있고,
// 실제로 어떻게 동작하는지(중괄호 {} 안의 코드)는 들어있지 않습니다.
// 그 실제 동작은 이 인터페이스를 "implements"하는 클래스들이 각자 채워 넣습니다.
//
// 왜 이렇게 나눠서 쓸까요?
// - 예를 들어 "은행 계좌"라는 개념 하나에도 일반 입출금 계좌, 저축 계좌, 마이너스 통장 등
//   종류가 다양할 수 있습니다.
// - 이 계좌들은 세부 동작 방식은 달라도, "입금할 수 있다", "출금할 수 있다",
//   "잔액을 조회할 수 있다"는 공통 규칙(약속)은 똑같이 지켜야 합니다.
// - 인터페이스로 이 공통 규칙을 미리 정해두면, 나중에 계좌 종류가 늘어나도
//   Main.java 같은 다른 코드는 "BankAccount 타입"으로만 다루면 되므로
//   구체적으로 어떤 계좌인지 몰라도 동일한 방식으로 사용할 수 있습니다.
//   (이런 성질을 "다형성(polymorphism)"이라고 부릅니다.)
public interface BankAccount {

    // 인터페이스 안의 메서드는 기본적으로 public이며, 몸통({}) 없이 세미콜론(;)으로 끝납니다.
    // "이 기능을 반드시 구현해야 한다"는 규칙만 정의하는 것입니다.

    String getOwner();      // 예금주 이름을 반환해야 함

    long getBalance();      // 현재 잔액을 반환해야 함

    void deposit(long amount); // 입금 기능이 있어야 함

    boolean withdraw(long amount); // 출금 기능이 있어야 함 (성공/실패를 알려줌)
}
